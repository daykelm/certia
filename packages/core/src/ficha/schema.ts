import { z } from "zod";

/**
 * Definition of an actuación ficha (F-03).
 *
 * A ficha is configuration, not code: adding a new kind of actuación
 * means writing a file that satisfies this schema.
 * Published versions are immutable (PROJECT.md, decision D3).
 *
 * Keys are in English; field ids, labels and document types are data
 * and mirror the official (Spanish) ficha.
 */

const IDENTIFIER = /^[a-z][a-z0-9_]*$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;

export const FIELD_TYPES = ["text", "number", "integer", "boolean", "date", "enum", "region"] as const;

export const FieldSchema = z
  .object({
    id: z.string().regex(IDENTIFIER, "id must be snake_case and start with a letter"),
    label: z.string().min(1),
    type: z.enum(FIELD_TYPES),
    options: z.array(z.string().min(1)).optional(),
    unit: z.string().optional(),
    required: z.boolean().default(true),
    min: z.number().optional(),
    max: z.number().optional(),
    /** Where the value comes from: "manual" or "document:<type>" (for AI extraction, F-05). */
    source: z.string().default("manual"),
    help: z.string().optional(),
  })
  .refine((f) => f.type !== "enum" || (f.options && f.options.length > 0), {
    message: "enum fields need options",
  });

export const RequiredDocumentSchema = z.object({
  type: z.string().regex(IDENTIFIER),
  label: z.string().min(1),
  required: z.boolean().default(true),
  /** Boolean expression over the fields; when false, the document does not apply. */
  condition: z.string().optional(),
  /** The document is generated by Certia from a template (F-09). */
  generated: z.boolean().default(false),
  /** Ficha fields extracted from this document (F-05). */
  extract: z.array(z.string()).default([]),
});

export const GroupingSchema = z.object({
  required: z.boolean().default(false),
  /** Keys that must match to group: expediente columns (region, year) or ficha fields. */
  keys: z.array(z.string()).default([]),
  min_kwh: z.number().nonnegative().default(0),
});

export const TemplateSchema = z.object({
  id: z.string().regex(IDENTIFIER),
  document: z.string().regex(IDENTIFIER),
  file: z.string().min(1),
  optional_clauses: z
    .array(z.object({ id: z.string().regex(IDENTIFIER), label: z.string().min(1) }))
    .default([]),
});

export const PackagingSchema = z.object({
  max_size_mb: z.number().positive().default(10),
  max_name_length: z.number().int().positive().default(100),
  forbidden_chars: z.string().default(".,;:/\\?*\"<>|'"),
  name_pattern: z.string().default("{reference}_{type}"),
});

export const TestCaseSchema = z.object({
  description: z.string().optional(),
  input: z.record(z.unknown()),
  expected_kwh: z.number(),
  tolerance: z.number().nonnegative().default(0.001),
});

export const FichaSchema = z
  .object({
    code: z.string().min(1),
    version: z.number().int().positive(),
    name: z.string().min(1),
    description: z.string().optional(),
    validity: z.object({
      from: z.string().regex(DATE),
      to: z.string().regex(DATE).optional(),
    }),
    fields: z.array(FieldSchema).min(1),
    /** Fixed values used by the formula (factors, lifetime...). May be lookup tables. */
    constants: z.record(z.unknown()).default({}),
    calculation: z.object({
      formula: z.string().min(1),
      decimals: z.number().int().min(0).max(6).default(0),
    }),
    tests: z.array(TestCaseSchema).min(1, "Every ficha needs at least one test case"),
    documents: z.array(RequiredDocumentSchema).default([]),
    grouping: GroupingSchema.default({}),
    templates: z.array(TemplateSchema).default([]),
    packaging: PackagingSchema.default({}),
  })
  .superRefine((f, ctx) => {
    const ids = new Set<string>();
    for (const field of f.fields) {
      if (ids.has(field.id)) ctx.addIssue({ code: "custom", message: `Duplicate field: ${field.id}` });
      ids.add(field.id);
    }
    for (const constant of Object.keys(f.constants)) {
      if (ids.has(constant)) {
        ctx.addIssue({ code: "custom", message: `Constant "${constant}" has the same name as a field` });
      }
    }
    const documentTypes = new Set(f.documents.map((d) => d.type));
    for (const template of f.templates) {
      if (!documentTypes.has(template.document)) {
        ctx.addIssue({
          code: "custom",
          message: `Template "${template.id}" generates "${template.document}", which is not in documents`,
        });
      }
    }
  });

export type Field = z.infer<typeof FieldSchema>;
export type RequiredDocument = z.infer<typeof RequiredDocumentSchema>;
export type Grouping = z.infer<typeof GroupingSchema>;
export type Template = z.infer<typeof TemplateSchema>;
export type Packaging = z.infer<typeof PackagingSchema>;
export type Ficha = z.infer<typeof FichaSchema>;
/** Input before defaults are applied (what is written in the YAML). */
export type FichaInput = z.input<typeof FichaSchema>;

export function parseFicha(input: unknown): Ficha {
  return FichaSchema.parse(input);
}

export function fichaKey(f: Pick<Ficha, "code" | "version">): string {
  return `${f.code}@v${f.version}`;
}
